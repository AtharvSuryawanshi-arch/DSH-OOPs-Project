CREATE SEQUENCE incident_reference_seq START WITH 1001;

CREATE TABLE users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_type       VARCHAR(20)  NOT NULL,
    name            VARCHAR(120) NOT NULL,
    email           VARCHAR(160) NOT NULL UNIQUE,
    password_hash   VARCHAR(100) NOT NULL,
    phone           VARCHAR(40),
    active          BOOLEAN      NOT NULL DEFAULT TRUE,
    department      VARCHAR(120),
    job_title       VARCHAR(120),
    experience_years INTEGER,
    max_capacity    INTEGER,
    available       BOOLEAN,
    created_at      TIMESTAMPTZ  NOT NULL,
    updated_at      TIMESTAMPTZ  NOT NULL
);
CREATE INDEX idx_users_type ON users (user_type);

CREATE TABLE categories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(40)  NOT NULL UNIQUE,
    name        VARCHAR(80)  NOT NULL UNIQUE,
    description VARCHAR(255),
    active      BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ  NOT NULL,
    updated_at  TIMESTAMPTZ  NOT NULL
);

CREATE TABLE services (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                 VARCHAR(40)  NOT NULL UNIQUE,
    name                 VARCHAR(120) NOT NULL UNIQUE,
    description          VARCHAR(500),
    business_criticality VARCHAR(20)  NOT NULL,
    active               BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at           TIMESTAMPTZ  NOT NULL,
    updated_at           TIMESTAMPTZ  NOT NULL,
    CONSTRAINT chk_service_criticality
        CHECK (business_criticality IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL'))
);

CREATE TABLE technician_skills (
    technician_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    category_id   BIGINT NOT NULL REFERENCES categories (id) ON DELETE CASCADE,
    PRIMARY KEY (technician_id, category_id)
);

CREATE TABLE sla_policies (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name               VARCHAR(120) NOT NULL,
    priority           VARCHAR(10)  NOT NULL,
    service_id         BIGINT REFERENCES services (id) ON DELETE CASCADE,
    response_minutes   INTEGER      NOT NULL,
    resolution_minutes INTEGER      NOT NULL,
    warning_percent    INTEGER      NOT NULL DEFAULT 80,
    active             BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at         TIMESTAMPTZ  NOT NULL,
    updated_at         TIMESTAMPTZ  NOT NULL,
    CONSTRAINT chk_sla_priority CHECK (priority IN ('P1', 'P2', 'P3', 'P4')),
    CONSTRAINT chk_sla_response CHECK (response_minutes > 0),
    CONSTRAINT chk_sla_resolution CHECK (resolution_minutes > 0),
    CONSTRAINT chk_sla_warning CHECK (warning_percent BETWEEN 1 AND 99)
);
CREATE UNIQUE INDEX uq_sla_global_priority
    ON sla_policies (priority) WHERE service_id IS NULL;
CREATE UNIQUE INDEX uq_sla_service_priority
    ON sla_policies (priority, service_id) WHERE service_id IS NOT NULL;

CREATE TABLE incidents (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference              VARCHAR(30)  NOT NULL UNIQUE,
    title                  VARCHAR(200) NOT NULL,
    description            TEXT         NOT NULL,
    reporter_id            BIGINT       NOT NULL REFERENCES users (id),
    category_id            BIGINT       NOT NULL REFERENCES categories (id),
    service_id             BIGINT       NOT NULL REFERENCES services (id),
    impact                 VARCHAR(20)  NOT NULL,
    urgency                VARCHAR(20)  NOT NULL,
    priority               VARCHAR(10)  NOT NULL,
    priority_score         INTEGER      NOT NULL,
    priority_rationale     VARCHAR(500),
    status                 VARCHAR(30)  NOT NULL,
    assigned_technician_id BIGINT REFERENCES users (id),
    affected_users         INTEGER      NOT NULL DEFAULT 1,
    auto_classified        BOOLEAN      NOT NULL DEFAULT FALSE,
    classification_confidence DOUBLE PRECISION,
    created_at             TIMESTAMPTZ  NOT NULL,
    updated_at             TIMESTAMPTZ  NOT NULL,
    acknowledged_at        TIMESTAMPTZ,
    resolved_at            TIMESTAMPTZ,
    closed_at              TIMESTAMPTZ,
    response_due_at        TIMESTAMPTZ,
    resolution_due_at      TIMESTAMPTZ,
    response_warning_at    TIMESTAMPTZ,
    resolution_warning_at  TIMESTAMPTZ,
    response_breached      BOOLEAN      NOT NULL DEFAULT FALSE,
    resolution_breached    BOOLEAN      NOT NULL DEFAULT FALSE,
    response_warning_sent  BOOLEAN      NOT NULL DEFAULT FALSE,
    resolution_warning_sent BOOLEAN     NOT NULL DEFAULT FALSE,
    escalation_level       INTEGER      NOT NULL DEFAULT 0,
    last_escalated_at      TIMESTAMPTZ,
    duplicate_of_id        BIGINT REFERENCES incidents (id) ON DELETE SET NULL,
    duplicate_score        DOUBLE PRECISION,
    resolution_notes       TEXT,
    closure_notes          TEXT,
    feedback_rating        INTEGER,
    feedback_comment       VARCHAR(1000),
    version                BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT chk_incident_impact
        CHECK (impact IN ('LOW', 'MEDIUM', 'HIGH', 'EXTREME')),
    CONSTRAINT chk_incident_urgency
        CHECK (urgency IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    CONSTRAINT chk_incident_priority
        CHECK (priority IN ('P1', 'P2', 'P3', 'P4')),
    CONSTRAINT chk_incident_feedback
        CHECK (feedback_rating IS NULL OR feedback_rating BETWEEN 1 AND 5)
);
CREATE INDEX idx_incidents_status ON incidents (status);
CREATE INDEX idx_incidents_priority ON incidents (priority);
CREATE INDEX idx_incidents_reporter ON incidents (reporter_id);
CREATE INDEX idx_incidents_technician ON incidents (assigned_technician_id);
CREATE INDEX idx_incidents_created ON incidents (created_at DESC);
CREATE INDEX idx_incidents_resolution_due ON incidents (resolution_due_at);

CREATE TABLE incident_comments (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id BIGINT      NOT NULL REFERENCES incidents (id) ON DELETE CASCADE,
    author_id   BIGINT      NOT NULL REFERENCES users (id),
    message     TEXT        NOT NULL,
    internal    BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_comments_incident ON incident_comments (incident_id, created_at);

CREATE TABLE incident_audit (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id BIGINT       NOT NULL REFERENCES incidents (id) ON DELETE CASCADE,
    actor_id    BIGINT REFERENCES users (id) ON DELETE SET NULL,
    action      VARCHAR(80)  NOT NULL,
    from_state  VARCHAR(30),
    to_state    VARCHAR(30),
    description VARCHAR(1000) NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL
);
CREATE INDEX idx_audit_incident ON incident_audit (incident_id, created_at);
CREATE INDEX idx_audit_created ON incident_audit (created_at DESC);

CREATE TABLE notifications (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    incident_id  BIGINT REFERENCES incidents (id) ON DELETE SET NULL,
    channel      VARCHAR(20)  NOT NULL,
    type         VARCHAR(40)  NOT NULL,
    title        VARCHAR(200) NOT NULL,
    message      VARCHAR(1000) NOT NULL,
    is_read      BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at   TIMESTAMPTZ  NOT NULL,
    CONSTRAINT chk_notification_channel CHECK (channel IN ('IN_APP', 'EMAIL'))
);
CREATE INDEX idx_notifications_recipient
    ON notifications (recipient_id, is_read, created_at DESC);

CREATE TABLE system_settings (
    setting_key   VARCHAR(80) PRIMARY KEY,
    setting_value VARCHAR(255) NOT NULL,
    updated_at    TIMESTAMPTZ  NOT NULL
);

DROP TABLE IF EXISTS tasks;
